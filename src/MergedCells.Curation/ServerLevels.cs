using System.Globalization;
using System.Text;
using MergedCells.Core;

namespace MergedCells.Curation;

// supabase/levels.sql: every shipped level's ID, layout fingerprint and par, which the server checks each score against
internal static class ServerLevels
{
    public static string Write(IEnumerable<Level> levels)
    {
        ArgumentNullException.ThrowIfNull(levels);
        var rows = levels.OrderBy(level => level.Id).Select(level =>
            string.Create(CultureInfo.InvariantCulture, $"  ({level.Id}, '{LevelFingerprint.Of(level)}', {level.Par})"));
        return new StringBuilder()
            .Append("-- Generated by the curation tool (promote, retire and server-levels). Don't edit by hand.\n")
            .Append("-- Rows are never deleted, so an older build's layouts and retired levels stay valid.\n")
            .Append("insert into game.levels (id, layout, par) values\n")
            .Append(string.Join(",\n", rows))
            .Append("\non conflict (id, layout) do nothing;\n")
            .ToString();
    }
}
